case "$stage" in
  smoke)
    if smoke; then echo "S083-SMOKE-DONE"; else echo "S083-SMOKE-FAILED"; exit 1; fi ;;
  generate)
    if generate "${2:-}"; then echo "S083-GENERATE-DONE"; else echo "S083-GENERATE-FAILED"; exit 1; fi ;;
  merge)
    if merge "${2:-}"; then echo "S083-MERGE-DONE"; else echo "S083-MERGE-FAILED"; exit 1; fi ;;
  curve)
    if curve "${2:-}"; then echo "S083-CURVE-DONE"; else echo "S083-CURVE-FAILED"; exit 1; fi ;;
  read)
    if read_command "${2:-}"; then echo "S083-READ-DONE"; else echo "S083-READ-FAILED"; exit 1; fi ;;
  verify)
    if verify "${2:-}"; then echo "S083-VERIFY-DONE"; else echo "S083-VERIFY-FAILED"; exit 1; fi ;;
  apply)
    if [[ $# -eq 3 ]] && apply "$2" "$3"; then echo "S083-APPLY-DONE"; else echo "S083-APPLY-FAILED"; exit 1; fi ;;
  *)
    echo "usage: $0 smoke | curve N | generate N | merge N | read N | verify [N] | apply FIT TREE" >&2
    exit 2 ;;
esac
