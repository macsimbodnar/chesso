#!/usr/bin/env bash
# S083's corpus: how many games of S082's recipe the corpus that ships holds,
# read off a held-out curve under a datagen budget stated before generation
# (DEC-259), the node budget held at 100000, then the fit pasted for S083's one
# SPRT (adocs/data/S083_sprt.sh).
#
#   adocs/data/S083_corpus.sh smoke           # 600 games: the day's rate, the abort rule
#   adocs/data/S083_corpus.sh curve 0         # stage 0: the curve on S082's pool, no datagen
#   adocs/data/S083_corpus.sh generate N      # stage N's chunks, N = 1 .. NIGHTS; resumable
#   adocs/data/S083_corpus.sh merge N         # stage N's training pool
#   adocs/data/S083_corpus.sh curve N         # stage N's curve, then its reading
#   adocs/data/S083_corpus.sh read N          # the reading alone, over the fits on disk
#   adocs/data/S083_corpus.sh verify [N]      # the fixed set, the chunks, stage N's pool
#   adocs/data/S083_corpus.sh apply FIT TREE  # the chosen fit into TREE's src/, built and gated
#
# generate, merge and curve N >= 1 need MODE=s082 or MODE=none in the
# environment, the coordinator's statement of which engine generates (below);
# the stage refuses when the datagen binary says otherwise. Each stage prints
# S083-<STAGE>-DONE or S083-<STAGE>-FAILED as its last stdout line, the reasons
# above a FAILED, so any of them runs detached under a four-exit watcher
# (WATCHERS). OUT defaults to .tuning/s083 (DEC-235: a run's outputs stay
# with the run; the readings go to adocs/data/ and the step file).
#
# ============================================================================
# PRE-REGISTRATION -- written 2026-10-22 in S083's phase 1, blind (DEC-260:
# S111's SPRT held the machine), before any of it ran. Nothing below the line
# changes once `curve 0` has started; a change is a dated section in the step
# file and a decision.
# ============================================================================
#
# THE BUDGET, IN NIGHTS: NIGHTS=2. A night is ten chunks of 12000 games,
# 120000 games, 11.1 h at the 10790 games an hour S082's pool ran at overnight
# (122749 games with a row in the 11 h 22 m 33 s between its log's start and
# its files' last write, adocs/data/S082_pool.log and S082's record), 10.3 h
# at the top-up's 11651 (27252 games in 8420 s). At most twenty chunks are
# generated, whatever the curve says.
#
# THE NODE BUDGET, HELD: 100000 a move, S065's and S082's. One change at a
# time: this step scales games at a held budget and does not also move the
# budget. 100000 is where S082's pool and the fixed validation set were
# played (DEC-275), so the curve's first points cost no datagen and every fit
# is read on games of its own budget. The 5000 the generator defaults to, and
# that a forum post illustrates, is another corpus and another verdict.
#
# THE RECIPE, S082's outcome (a): leaf qs, 46 rows a game. Chunks are written
# with `--leaf qs` alone. A leaf is a function of its FEN and the walks never
# touch a game (S082's phase 2: the root files of `--leaf root` and `--leaf
# root,qs,pv` from one seed byte-identical), so the qs rows are the ones a
# three-leaf run writes, at a third of the disk. Every other datagen setting is
# its default, as S082's: 8 random plies, 400 max plies, opening limit 400,
# resign at 2000 for 6 plies, quiet limit 1000, 16 MB of hash a worker.
#
# WHICH ENGINE GENERATES, MODE. DEC-294: the corpus is generated by the engine
# that ships. S082's pool was played by datagen sha256 4b0e2848..., built at
# `5b0e170`, bench 6042933.
#   MODE=s082  S111 read H0 or no verdict, nothing was committed, and the
#              datagen binary is that same one (the main tree's build/ held it
#              on 2026-10-22). The pool's training side -- 137998 games,
#              11690184 qs rows -- is stage 0, and each stage's chunks join it,
#              DEC-296's form: the same binary, seeds that meet none of the
#              pool's, ids moved above it.
#   MODE=none  S111 landed: another engine (its datagen carries the two
#              continuation tables). Stage 0, the old engine's pool, is
#              informational: its figures are reported, readable or not, and
#              never decide; stage 1 always runs -- twelve chunks, 144000
#              games, at least the pool's training games -- and every stage's
#              pool is chunks alone. Stage 2 runs on stage 1's reading.
#   Under MODE=s082 stage 0 decides as every stage does (THE READING).
# The binary decides which applies and MODE must say the same, or the stage
# refuses. No pool mixes two engines. DEC-304 (pending, the coordinator's).
#
# FROZEN BINARIES. No stage runs build/'s binaries in place: tools/gate.sh
# rebuilds build/ on any commit. `smoke` and each `generate N` copy datagen
# into $OUT and record the copy's sha256; every chunk re-hashes the copy
# against that record before it runs, and against the run's one datagen
# sha256 ($OUT/chunks/datagen.sha256). Each `curve N` copies the tuner the
# same way and re-hashes it before every fit.
#
# CHUNKS AND SEEDS. Chunk k, k = 0 .. 19: `datagen --out
# $OUT/chunks/cKK.qs.tsv --leaf qs --games 12000 --nodes 100000 --threads 12
# --seed $((2026102200 + 100 * k))`; worker i of 12 is seeded seed + i, so the
# chunks' worker seeds, 2026102200 to 2026104111, meet none of the pool's
# (20261013 to 20261024, 2026102000 to 2026102011). Stage N holds chunks 0 to
# 10N - 1 (s082) or 0 to 11 then 0 to 19 (none). The smoke runs 600 games at
# seed 2026102100.
#
# THE TRAINING POOL OF A STAGE. Stage 0: S082's `pool.tsv.qs.train`, sha256
# 8e9645b3.... Stage N: under s082 that file byte for byte and then the stage's
# chunks; under none the chunks alone; each chunk's game ids moved up by
# 2000000 + 100000 k (S083_corpus.py merge). The fixed validation set is
# S082's, its three views checked against their sha256 before every curve.
#
# THE FIT, S082's compare's except the corpus: `tuner --data CORPUS --holdout
# .tuning/s082/pool.tsv.qs.validation --freeze tempo,piece_placement --epochs
# 5000 --report 100 --patience 20 --lambda 0 --seed 1 --threads 12`, K fitted
# from each corpus's own rows, the fits starting from the shipped constants
# (DEC-298). The qs view only: it is primary (DEC-275), and the root view's
# fits decided nothing in S082 and mostly measured K (DEC-298). Corpora are
# `tools/corpus_split.py sample --per-game 46 --seed S --rows R` with all three
# views of the set named, as S082's were. No dedupe, S082's setting: the
# recipe the candidate is built on was chosen without one, and S076 owns the
# question. The duplicate share of the top rung is printed, deciding nothing.
#
# THE CURVE OF A STAGE. C is the stage pool's capacity at 46 a game -- the rows
# `sample` writes when it takes every game, counted by S083_corpus.py
# capacity. The rungs are C, C/2, C/4, ... down to the last at or above
# 1000000 rows, each sampled under seed 1 -- `sample` takes games in its
# seed's order, so a rung's games are the first half of the rung above's, the
# curve nested. The smallest rung is sampled under seeds 1 to 5 as well.
# Stage 0 adds the second reading the step file asks for: every game of S082's
# training side at 8 and at every row a game, beside 46's top rung -- rows a
# game at a fixed game count.
#
# THE READING, by S083_corpus.py read, mechanically:
#   1. L(R) is the `best:` line's validation figure of rung R's seed-1 fit.
#   2. s is the sample standard deviation (n - 1) of the smallest rung's five
#      fits; m = 1.645 * sqrt(2) * s -- one difference, one-sided at 95 %.
#      Taken where the five corpora overlap least, so it overstates the noise
#      at the top, where the corpora are larger: the rule errs toward spending
#      no further night. s from five draws is loose (a 90 % interval runs 0.65 s
#      to 2.37 s, chi-square on 4 degrees of freedom), as S082 said of its own.
#   3. d = L(C/2) - L(C), the top doubling's gain.
#   4. Outcome (c), unreadable, and nothing is chosen, when s is above 1e-3, a
#      sample or a fit is refused or missing, or a smaller rung fits better
#      than C by more than m (more rows hurt). Not at stage 0 under
#      MODE=none: there those conditions are reported, and the reading leads
#      to stage 1 whatever they say.
#   5. Otherwise, if d > m and a stage of the budget is left: still
#      descending -- stage N + 1 is generated. Under MODE=none stage 0 always
#      leads to stage 1 (DEC-294), readable or not.
#   6. Otherwise stop. THE CANDIDATE is the top rung, C rows: every game of the
#      stage's pool at 46 rows a game, its seed-1 fit. One candidate, one SPRT.
#   7. Printed beside, deciding nothing: every rung, every doubling's gain
#      against m -- the record of whether "more rows still helps" at 823
#      parameters -- K, the best epoch, a fit that did not improve, the second
#      reading (a density beating 46 by more than m at the same games is
#      printed as a finding for the coordinator, never acted on here: the
#      density is S082's), and the duplicate share.
#   If the candidate's fit moves no constant (`apply` finds the sources
#   unchanged), no SPRT is owed and the zero is recorded (S076's rule 3).
#
# THE THREE OUTCOMES. (a) stop at stage 0 under s082: the candidate is S082's
# training side, no datagen spent of the budget. (b) stop at stage 1 or 2:
# the candidate holds the pool and the stages' chunks, or the chunks alone
# under none. (c) unreadable: nothing is chosen, the step stays open, and the
# coordinator writes what went wrong before anything re-runs.
#
# ABORT RULE, AND THE GATING, ENFORCED BY THIS SCRIPT. The rule: more than 1 %
# of the positions that passed the filter refused as truncated, aborted or
# uncertified (S082's rule; terminal refusals printed, never gated), or under
# 8333 games an hour -- S082's 18 h for 150000 games, as a rate. (a) `smoke`
# applies it to its 600 games and only a pass writes $OUT/smoke/<sha>/pass,
# naming the datagen sha256 it tested; `generate` refuses unless a pass names
# the very copy it is about to run. (b) Every chunk applies it to its own log
# (`S083_corpus.py chunk-check --abort-share 1 --rate-floor 8333`); when it
# fires, $OUT/chunks/ABORTED is written, the stage ends FAILED, and every
# later `generate` refuses until the coordinator has read it and removed it.
# (c) `generate N` refuses unless stage N - 1's reading, under the same MODE,
# printed READ-OUTCOME continue -- except stage 1 under MODE=none, which
# always runs. A chunk that fails its structural check stops the stage; the
# next run moves it aside and plays it again, once. Twice is the
# coordinator's.
#
# A POWER CUT. datagen flushes each game; a chunk counts only once its rows
# match its log and its sha256 is written beside it in cKK.done, after a sync.
# A run that finds a chunk without .done moves its files to chunks/cut/ (kept,
# never deleted) and plays the chunk again from its seed: the same binary and
# seed play the same games, each worker deterministic at a node budget. A cut
# loses at most the chunk in flight, 67 min at 10790 games an hour. A chunk
# whose .done no longer matches its file's sha256 is treated the same way.
# `curve` skips a rung whose fit log already has its `best:` line, so it
# resumes too.
#
# MACHINE HOURS, from measured throughput only. Generation: a chunk 67 min, a
# night 11.1 h (10.3 h at the top-up's rate); twelve chunks (none's stage 1)
# 13.3 h; the smoke about 3 min (S082's 600-game smokes, 192 s and 193 s, ran
# three leaves). Fits: a minute a million rows at the 2000 to 2700 epochs
# patience stopped S082's qs-view fits at (its compare's thirteen 1 M-row
# qs-view fits ran 48 to 93 s by their files' times; S262's 10.8 M-row fit
# 2100 epochs in 9 m 03 s, about 0.024 s an epoch a million rows), two at most
# at 5000, and about 15 s of loading a fit. Passes over a pool, scaled by its
# size from S082's compare, whose samples over the 0.92 GB training file took
# 13 to 15 s for a few thousand games and 24 to 27 s when they read nearly
# every game (its files' times): a sample about 15 s plus 12 s for the whole
# file, per 0.92 GB; the capacity pass about 30 s per 0.92 GB; the sha256
# checks seconds. So, typical and worst (every fit at 5000 epochs), with the
# watcher ceiling at twice the worst:
#   stage 0 (0.92 GB, 9 fits, 29.9 M rows fitted, 9 samples):
#     capacity 0.5 min, samples 3.5 min, fits 32 / 62 min -- 36 / 66 min,
#     ceiling 2 h 15 m
#   stage 1, s082 (1.71 GB, 8 fits, 27.6 M rows, 8 samples):
#     capacity 1 min, samples 5 min, fits 30 / 57 min -- 36 / 63 min,
#     ceiling 2 h 10 m
#   stage 2, s082 (2.5 GB, 9 fits, 37.3 M rows, 9 samples):
#     capacity 1.5 min, samples 8 min, fits 40 / 77 min -- 50 / 87 min,
#     ceiling 3 h
#   stage 1, none (0.95 GB, 7 fits, 17.8 M rows, 7 samples): 23 / 41 min,
#     ceiling 1 h 30 m; stage 2, none (1.58 GB, 8 fits, 25.7 M rows):
#     34 / 60 min, ceiling 2 h.
# A merge about 2 to 5 min (S082's merge wrote 2.9 GB in 2 min), ceiling
# 30 min. Every stage under DEC-155's four hours but `generate`, which is
# night work.
#
# DISK. A chunk's qs file about 79 MB (S082's qs rows, 6599 bytes a game); a
# night 0.79 GB; a stage's merged pool 0.92 GB plus 0.79 GB a night under
# s082; a stage's samples 79 MB a million rows (S082's 46-a-game sample),
# about 2.4 GB at stage 0, 2.2 GB at stage 1 and 3.0 GB at stage 2. The whole
# budget under s082 is about 13 GB; a read stage's samples may be removed once
# its reading is recorded, each being reproducible from its seed and its
# pool's sha256. Every stage refuses to start under 6 GB free; 20 GB were free
# on 2026-10-22.
#
# OPEN FINDINGS (BUGS as scoped by DEC-171): written at launch by the
# coordinator, in the step file, against plan.md's Open list on the day.
# ============================================================================

