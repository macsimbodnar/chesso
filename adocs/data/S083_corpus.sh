  fi
}

chunk_name() { printf 'c%02d' "$1"; }

# A done chunk is one whose file still has the sha256 its .done recorded.
chunk_is_done() {
  local name="$1" recorded
  [[ -f "$OUT/chunks/$name.done" && -f "$OUT/chunks/$name.qs.tsv" ]] || return 1
  recorded=$(sed -n 's/^sha256 //p' "$OUT/chunks/$name.done")
  [[ -n "$recorded" &&
     "$recorded" == "$(sha256sum "$OUT/chunks/$name.qs.tsv" | cut -d' ' -f1)" ]]
}

# The day's rate and the abort rule, on a frozen copy of the build's datagen,
# in a directory named by that copy's sha256. A pass writes $dir/pass, naming
# the sha it tested; `generate` refuses without a pass for the binary it runs.
smoke() {
  enough_disk || return 1
  [[ -x "$datagen" ]] || { say "no datagen at $datagen"; return 1; }
  local live dir copy sha stamp started status elapsed rate report rc
  live=$(sha256sum "$datagen" | cut -d' ' -f1)
  dir="$OUT/smoke/${live:0:12}"
  if [[ -f "$dir/pass" ]]; then
    cat "$dir/pass"
    say "datagen ${live:0:12} passed its smoke before"
    return 0
  fi
  [[ ! -e "$dir/smoke.qs.tsv" ]] ||
    { say "$dir holds a smoke that did not pass; move it aside first"; return 1; }
  copy="$dir/datagen"
  sha=$(freeze_binary "$datagen" "$copy") || { echo "$sha"; return 1; }
  stamp=$(engine_stamp "$dir/engine.diff") || return 1
  {
    echo "S083 smoke"
    echo "started   $(date -Iseconds)"
    echo "engine    $stamp"
    echo "mode      $(mode_of "$sha") (by the binary)"
    binary_line datagen "$copy"
    echo "command   datagen --out $dir/smoke.qs.tsv --leaf qs --games $SMOKE_GAMES --nodes $NODES --threads $THREADS --seed $SMOKE_SEED"
  } > "$dir/smoke.log"
  check_copy "$copy" || return 1
  started=$(date +%s)
  "$copy" --out "$dir/smoke.qs.tsv" --leaf qs --games "$SMOKE_GAMES" \
      --nodes "$NODES" --threads "$THREADS" --seed "$SMOKE_SEED" \
      2>> "$dir/smoke.log"
  status=$?
  elapsed=$(( $(date +%s) - started ))
  { echo "exit      $status"; echo "elapsed   $elapsed s"; } >> "$dir/smoke.log"
  cat "$dir/smoke.log"
  (( status == 0 )) || { say "datagen exited $status"; return 1; }
  (( elapsed > 0 )) || elapsed=1
  rate=$(( SMOKE_GAMES * 3600 / elapsed ))
  say "rate      $rate games an hour; $(awk -v r="$rate" -v g="$CHUNK_GAMES" \
      'BEGIN { printf "a chunk %.0f min, a night of ten %.1f h, twelve chunks %.1f h", g * 60 / r, 10 * g / r, 12 * g / r }')"

  # The abort rule, by the helper every chunk is checked with: truncated,
  # aborted and uncertified against 1 % of what passed, terminal not gated,
  # and the 8333 games an hour floor. Exit 2 is the rule firing.
  report=$(python3 "$helper" chunk-check "$dir/smoke.qs.tsv" "$dir/smoke.log" \
             "$SMOKE_GAMES" --abort-share "$ABORT_SHARE_PCT" \
             --rate-floor "$RATE_FLOOR" 2>&1)
  rc=$?
  echo "$report"
  if (( rc == 2 )); then
    say "abort: the rule fires on the smoke; generate refuses this binary"
    return 1
  fi
  (( rc == 0 )) || return 1
  {
    echo "datagen $sha"
    echo "rate $rate"
    echo "passed $(date -Iseconds)"
  } > "$dir/pass.tmp" && mv "$dir/pass.tmp" "$dir/pass"
  sync
  say "pass      $dir/pass"
}

generate() {
  local n="$1" mode target sha copy k name seed started status elapsed rc
  check_stage_number "$n" 1 || return 1
  enough_disk || return 1
  mkdir -p "$OUT/chunks/cut" "$OUT/bin" || return 1

  # A fired abort rule stops every later run until the coordinator, having
  # read it, removes the marker.
  if [[ -e "$OUT/chunks/ABORTED" ]]; then
    cat "$OUT/chunks/ABORTED"
    say "refused: the abort rule fired; the coordinator decides, and removes $OUT/chunks/ABORTED to go on"
    return 1
  fi

  # This stage's frozen datagen: the only binary its chunks run.
  copy="$OUT/bin/datagen.stage$n"
  sha=$(freeze_binary "$datagen" "$copy") || { echo "$sha"; return 1; }
  require_mode "$sha" || return 1
  mode="$MODE"

  # One binary for every chunk of the run's pool, whatever stage made it.
  if [[ -f "$OUT/chunks/datagen.sha256" ]]; then
    if [[ "$(cat "$OUT/chunks/datagen.sha256")" != "$sha" ]]; then
      say "refused: the chunks so far were played by datagen $(cut -c1-12 "$OUT/chunks/datagen.sha256"), this stage's copy is ${sha:0:12}; a pool never mixes two"
      return 1
    fi
  else
    echo "$sha" > "$OUT/chunks/datagen.sha256"
  fi

  # The abort rule's first half: the smoke passed on this very binary.
  local pass="$OUT/smoke/${sha:0:12}/pass"
  if [[ ! -f "$pass" || "$(sed -n 's/^datagen //p' "$pass")" != "$sha" ]]; then
    say "refused: no smoke pass for datagen ${sha:0:12} ($pass); run smoke first"
    return 1
  fi

  # The reading that sends a stage: stage N - 1's, under this MODE, printed
  # READ-OUTCOME continue. Stage 1 under MODE=none runs whatever stage 0 read.
  if ! [[ "$mode" == none && "$n" == 1 ]]; then
    local reading="$OUT/curve/s$(( n - 1 ))/reading.txt"
    if ! { [[ -f "$reading" ]] &&
           head -n 1 "$reading" | grep -q "mode $mode," &&
           grep -qx 'READ-OUTCOME continue' "$reading"; }; then
      say "refused: stage $(( n - 1 ))'s reading under mode $mode ($reading) did not print READ-OUTCOME continue"
      return 1
    fi
  fi

  target=$(chunks_for "$n" "$mode")
  local stamp
  stamp=$(engine_stamp "$OUT/chunks/engine.diff") || return 1
  say "S083 generate, stage $n, mode $mode: chunks 0 to $(( target - 1 ))"
  say "engine    $stamp"
  binary_line datagen "$copy"

  for (( k = 0; k < target; k++ )); do
    name=$(chunk_name "$k")
    if chunk_is_done "$name"; then
      say "$name done before, sha256 checked"
      continue
    fi

    # A chunk without a matching .done: a cut, a failure or a damaged file.
    # Its files are kept under cut/, and the chunk is played again from its
    # seed -- once after a failure; a second failure is the coordinator's.
    if compgen -G "$OUT/chunks/$name.*" > /dev/null; then
      local aside
      aside="$OUT/chunks/cut/$name.$(date +%Y%m%dT%H%M%S)"
      if compgen -G "$OUT/chunks/cut/$name.*" > /dev/null &&
         [[ -f "$OUT/chunks/$name.failed" ]]; then
        say "refused: $name failed before and was played again; it is the coordinator's now (see chunks/cut/)"
        return 1
      fi
      mkdir -p "$aside" && mv "$OUT/chunks/$name".* "$aside"/ || return 1
      say "$name: moved what a run left of it to $aside"
    fi

    seed=$(( SEED_BASE + SEED_STRIDE * k ))
    {
      echo "S083 chunk $name"
      echo "started   $(date -Iseconds)"
      echo "engine    $stamp"
      binary_line datagen "$copy"
      echo "command   datagen --out $OUT/chunks/$name.qs.tsv --leaf qs --games $CHUNK_GAMES --nodes $NODES --threads $THREADS --seed $seed"
    } > "$OUT/chunks/$name.log"
    check_copy "$copy" | tee -a "$OUT/chunks/$name.log"
    (( PIPESTATUS[0] == 0 )) || return 1
    started=$(date +%s)
    "$copy" --out "$OUT/chunks/$name.qs.tsv" --leaf qs \
        --games "$CHUNK_GAMES" --nodes "$NODES" --threads "$THREADS" \
        --seed "$seed" 2>> "$OUT/chunks/$name.log"
    status=$?
    elapsed=$(( $(date +%s) - started ))
    { echo "exit      $status"; echo "elapsed   $elapsed s"; } >> "$OUT/chunks/$name.log"
    sync

    # The structure against the log, then the abort rule's second half on
    # this chunk's own figures: 1 % and 8333 games an hour. Exit 2 is the rule.
    local report chunk_line
    report=$(python3 "$helper" chunk-check "$OUT/chunks/$name.qs.tsv" \
               "$OUT/chunks/$name.log" "$CHUNK_GAMES" \
               --abort-share "$ABORT_SHARE_PCT" --rate-floor "$RATE_FLOOR" 2>&1)
    rc=$?
    echo "$report" >> "$OUT/chunks/$name.log"
    if (( rc == 2 )); then
      echo "$report"
      {
        echo "chunk     $name"
        echo "fired     $(date -Iseconds)"
        echo "$report"
      } > "$OUT/chunks/ABORTED"
      sync
      say "abort rule fired on $name: generation stops (S083-GENERATE-FAILED); the coordinator's"
      return 1
    fi
    if (( rc != 0 )); then
      echo "$report"
      date -Iseconds > "$OUT/chunks/$name.failed"
      say "$name failed (datagen exit $status); the next run moves it aside and plays it again"
      return 1
    fi
    chunk_line=$(grep '^chunk ' <<< "$report")
    {
      echo "$chunk_line"
      echo "rows $(sed -E 's/^chunk [^:]+: ([0-9]+) rows.*/\1/' <<< "$chunk_line")"
      echo "sha256 $(sed -E 's/.*sha256 ([0-9a-f]+)$/\1/' <<< "$chunk_line")"
      echo "seed $seed"
      echo "elapsed $elapsed"
      echo "datagen $sha"
      grep -E '^(abort rule|rate):' <<< "$report"
      echo "finished $(date -Iseconds)"
    } > "$OUT/chunks/$name.done.tmp"
    mv "$OUT/chunks/$name.done.tmp" "$OUT/chunks/$name.done"
    sync
    say "$name: $chunk_line, $elapsed s"
  done

  local logs=()
  for (( k = 0; k < target; k++ )); do
    logs+=("$OUT/chunks/$(chunk_name "$k").log")
  done
  python3 "$helper" filters "${logs[@]}" | tee "$OUT/chunks/stage$n.filters"
  return "${PIPESTATUS[0]}"
}

merge() {
  local n="$1" mode target k name out base=()
  check_stage_number "$n" 1 || return 1
  require_mode || return 1
  enough_disk || return 1
  mode="$MODE"
  target=$(chunks_for "$n" "$mode")
  mkdir -p "$OUT/pool"
  out="$OUT/pool/train_$n.qs.tsv"
  [[ ! -e "$out" ]] || { say "$out exists; a training pool is never overwritten"; return 1; }
  if [[ -e "$OUT/pool/train_$n.log" ]]; then
    mv "$OUT/pool/train_$n.log" "$OUT/pool/train_$n.failed.$(date +%Y%m%dT%H%M%S).log" || return 1
  fi

  local chunks=()
  for (( k = 0; k < target; k++ )); do
    name=$(chunk_name "$k")
    chunk_is_done "$name" || { say "$name is not done; run generate $n"; return 1; }
    if [[ "$(sed -n 's/^datagen //p' "$OUT/chunks/$name.done")" != "$(cat "$OUT/chunks/datagen.sha256")" ]]; then
      say "refused: $name was played by another datagen than the run's"
      return 1
    fi
    chunks+=("$OUT/chunks/$name.qs.tsv:$k")
  done
  if [[ "$mode" == s082 ]]; then
    if [[ "$(cat "$OUT/chunks/datagen.sha256")" != "$S082_DATAGEN_SHA" ]]; then
      say "refused: MODE=s082, and the chunks' datagen is not S082's pool's"
      return 1
    fi
    base=(--base "$S082_TRAIN" --base-sha256 "$S082_TRAIN_SHA")
  fi

  {
    echo "S083 training pool, stage $n, mode $mode"
    echo "started   $(date -Iseconds)"
    binary_line helper "$helper"
    python3 "$helper" merge --out "$out" "${base[@]}" "${chunks[@]}"
    echo "status    $?"
    echo "finished  $(date -Iseconds)"
  } > "$OUT/pool/train_$n.log" 2>&1
  cat "$OUT/pool/train_$n.log"
  sync
  grep -q '^status    0$' "$OUT/pool/train_$n.log"
}

# The stage's training file and the sha256 it must have.
stage_pool() {
  local n="$1"
  if (( n == 0 )); then
    echo "$S082_TRAIN $S082_TRAIN_SHA"
    return
  fi
  local log="$OUT/pool/train_$n.log" sha
  sha=$(sed -nE "s|^merged $OUT/pool/train_$n.qs.tsv: .* sha256 ([0-9a-f]+)$|\1|p" "$log" 2>/dev/null)
  [[ -n "$sha" ]] || { say "no merged pool recorded in $log"; return 1; }
  echo "$OUT/pool/train_$n.qs.tsv $sha"
}

check_views() {
  local i
  for i in 0 1 2; do
    if [[ "$(sha256sum "${VIEWS[$i]}" | cut -d' ' -f1)" != "${VIEW_SHAS[$i]}" ]]; then
      say "the fixed validation set's ${VIEWS[$i]} is not the file S082 recorded"
      return 1
    fi
  done
  say "fixed set: the three views' sha256 are S082's"
}

# One corpus and its fit; skipped when its fit log already holds a best: line,
# so a stage cut short resumes. The sample is this stage's own file and is
# drawn again when its fit did not finish. The fit runs the stage's frozen
# tuner, $stage_tuner, re-hashed first.
stage_tuner=""
fit_cell() {
  local dir="$1" tag="$2" train="$3" rows="$4" per_game="$5" seed="$6"
  local corpus="$dir/cand_$tag.tsv" fit="$dir/fit_$tag"
  if [[ -f "$fit.log" ]] && grep -q '^best: ' "$fit.log"; then
    say "$tag fitted before"
    return 0
  fi
  rm -f "$corpus" "$fit.log" "$fit.hpp"
  python3 "$split" sample --in "$train" \
      --validation "${VIEWS[0]}" --validation "${VIEWS[1]}" \
      --validation "${VIEWS[2]}" --rows "$rows" --per-game "$per_game" \
      --seed "$seed" --out "$corpus" | tee -a "$dir/samples.log"
  (( PIPESTATUS[0] == 0 )) || { say "sample $tag refused"; return 1; }
  check_copy "$stage_tuner" || return 1
  # shellcheck disable=SC2086
  "$stage_tuner" --data "$corpus" --holdout "$HOLDOUT" --out "$fit.hpp" $FIT \
      > "$fit.log" 2>&1 || { say "fit $tag failed; see $fit.log"; return 1; }
  say "$tag: $(grep '^best: ' "$fit.log")"
}

curve() {
  local n="$1" pool train sha dir mode
  check_stage_number "$n" 0 || return 1
  enough_disk || return 1
  if (( n == 0 )); then
    mode=$(derived_mode) || return 1
  else
    require_mode || return 1
    mode="$MODE"
  fi
  pool=$(stage_pool "$n") || { echo "$pool"; return 1; }
  read -r train sha <<< "$pool"
  [[ "$(sha256sum "$train" | cut -d' ' -f1)" == "$sha" ]] ||
    { say "$train is not the file its record names"; return 1; }
  check_views || return 1

  dir="$OUT/curve/s$n"
  mkdir -p "$dir" || return 1

  # The stage's frozen tuner: every fit of the stage runs this copy, so a
  # rebuild of build/ mid-stage cannot change the fit under a recorded sha.
  local tsha
  stage_tuner="$dir/bin/tuner"
  tsha=$(freeze_binary "$tuner" "$stage_tuner") || { echo "$tsha"; return 1; }

  local stamp
  stamp=$(engine_stamp "$dir/engine.diff") || return 1
  {
    echo "S083 curve, stage $n, mode $mode"
    echo "started   $(date -Iseconds)"
    echo "engine    $stamp"
    echo "pool      $train, sha256 $sha"
    binary_line tuner "$stage_tuner"
    binary_line split "$split"
    binary_line helper "$helper"
    echo "python    $(python3 --version 2>&1)"
  } >> "$dir/curve.log"

  local densities="$PER_GAME"
  (( n == 0 )) && densities="$PER_GAME $SECOND_READING"
  local per_game_args=()
  for d in $densities; do per_game_args+=(--per-game "$d"); done
  if [[ ! -f "$dir/capacity.txt" ]]; then
    if ! python3 "$helper" capacity --in "$train" --validation "${VIEWS[0]}" \
           --validation "${VIEWS[1]}" --validation "${VIEWS[2]}" \
           "${per_game_args[@]}" > "$dir/capacity.tmp" 2>&1; then
      cat "$dir/capacity.tmp"
      rm -f "$dir/capacity.tmp"
      return 1
    fi
    mv "$dir/capacity.tmp" "$dir/capacity.txt"
  fi
  cat "$dir/capacity.txt" | tee -a "$dir/curve.log"

  local top
  top=$(sed -nE "s/^capacity: per-game $PER_GAME, ([0-9]+) rows,.*/\1/p" "$dir/capacity.txt")
  [[ -n "$top" ]] || { say "no capacity at $PER_GAME a game"; return 1; }

  # The rungs, halving from the top, the last at or above the floor.
  local rungs=() r="$top"
  while (( r >= LADDER_FLOOR )); do
    rungs+=("$r")
    r=$(( r / 2 ))
  done
  (( ${#rungs[@]} >= 2 )) || { say "the pool's $top rows give fewer than two rungs"; return 1; }
  local smallest="${rungs[-1]}"
  {
    for r in "${rungs[@]}"; do echo "rung $r"; done
    echo "seeds $smallest $SEEDS"
    if (( n == 0 )); then
      for d in $SECOND_READING; do
        echo "density $d $(sed -nE "s/^capacity: per-game $d, ([0-9]+) rows,.*/\1/p" "$dir/capacity.txt")"
      done
    fi
  } > "$dir/ladder.txt"
  cat "$dir/ladder.txt" | tee -a "$dir/curve.log"

  for r in "${rungs[@]}"; do
    fit_cell "$dir" "${r}_s1" "$train" "$r" "$PER_GAME" 1 | tee -a "$dir/curve.log"
    (( PIPESTATUS[0] == 0 )) || return 1
  done
  for s in $SEEDS; do
    (( s == 1 )) && continue
    fit_cell "$dir" "${smallest}_s$s" "$train" "$smallest" "$PER_GAME" "$s" | tee -a "$dir/curve.log"
    (( PIPESTATUS[0] == 0 )) || return 1
  done
  if (( n == 0 )); then
    local d rows
    for d in $SECOND_READING; do
      rows=$(sed -nE "s/^density $d ([0-9]+)$/\1/p" "$dir/ladder.txt")
      fit_cell "$dir" "dens$d" "$train" "$rows" "$d" 1 | tee -a "$dir/curve.log"
      (( PIPESTATUS[0] == 0 )) || return 1
    done
  fi

  # The top rung's duplicate share, by the engine's own key (S076's tool); its
  # output is a derived copy and is removed once counted.
  if [[ -x "$dedupe" && ! -f "$dir/dedupe.txt" ]]; then
    binary_line dedupe "$dedupe" >> "$dir/curve.log"
    "$dedupe" --in "$dir/cand_${top}_s1.tsv" --out "$dir/dedupe_probe.tsv" \
        > "$dir/dedupe.txt" 2>&1
    rm -f "$dir/dedupe_probe.tsv"
  fi
  [[ -f "$dir/dedupe.txt" ]] && sed 's/^/dedupe    /' "$dir/dedupe.txt" | tee -a "$dir/curve.log"

  echo "finished  $(date -Iseconds)" >> "$dir/curve.log"
  read_stage "$n" "$mode"
}

read_command() {
  local n="$1" mode
  check_stage_number "$n" 0 || return 1
  if (( n == 0 )); then
    mode=$(derived_mode) || { echo "$mode"; return 1; }
  else
    require_mode || return 1
    mode="$MODE"
  fi
  read_stage "$n" "$mode"
}

read_stage() {
  local n="$1" mode="$2" dir="$OUT/curve/s$1" status
  python3 "$helper" read "$dir" --stage "$n" --last-stage "$NIGHTS" \
      --mode "$mode" > "$dir/reading.txt" 2>&1
  status=$?
  cat "$dir/reading.txt"
  return "$status"
}

verify() {
  local n="${1:-}" k name failed=0
  check_views || failed=1
  if [[ "$(sha256sum "$S082_TRAIN" | cut -d' ' -f1)" == "$S082_TRAIN_SHA" ]]; then
    say "S082's training side: sha256 as recorded"
  else
    say "S082's training side is not the file S082 recorded"
    failed=1
  fi
  for done_file in "$OUT"/chunks/c*.done; do
    [[ -e "$done_file" ]] || continue
    name=$(basename "$done_file" .done)
    if chunk_is_done "$name" &&
       python3 "$helper" chunk-check "$OUT/chunks/$name.qs.tsv" \
           "$OUT/chunks/$name.log" "$CHUNK_GAMES" > /dev/null; then
      say "$name: rows against its log, sha256 against its .done"
    else
      say "$name: FAILS its checks"
      failed=1
    fi
  done
  if [[ -n "$n" ]] && (( n >= 1 )); then
    local pool train sha
    if pool=$(stage_pool "$n"); then
      read -r train sha <<< "$pool"
      if [[ "$(sha256sum "$train" | cut -d' ' -f1)" == "$sha" ]]; then
        say "stage $n's pool: sha256 as merged"
      else
        say "stage $n's pool is not the file its merge recorded"
        failed=1
      fi
    else
      echo "$pool"
      failed=1
    fi
  fi
  return "$failed"
}

# The chosen fit into TREE: pasted by .tuning/apply_fit.py, checked constant
# by constant by .tuning/verify_fit.py, the moves listed by .tuning/diff_fit.py
# against TREE's HEAD; then both builds, bench, and the fast suite in both,
# whose reds are the goldens the paste moved -- each re-derived by its script
# afterwards (DEC-142), never read off this run. TREE stays uncommitted.
apply() {
  local fit="$1" tree="$2" dir head
  [[ -f "$fit" ]] && grep -q '^// Fitted by tools/tuner' "$fit" ||
    { say "$fit is not a tuner header"; return 1; }
  git -C "$tree" rev-parse --is-inside-work-tree > /dev/null 2>&1 ||
    { say "$tree is not a git tree"; return 1; }
  git -C "$tree" diff --quiet HEAD -- src/eval_tables.hpp src/evaluation.cpp ||
    { say "$tree's evaluation sources differ from its HEAD already"; return 1; }
  head=$(git -C "$tree" rev-parse HEAD)
  dir="$OUT/apply"
  mkdir -p "$dir"
  say "S083 apply: $fit into $tree at ${head:0:12}"
  sha256sum "$fit" | tee "$dir/fit.sha256"

  python3 "$root/.tuning/apply_fit.py" "$fit" --root "$tree" | tee "$dir/apply_fit.txt"
  (( PIPESTATUS[0] == 0 )) || { say "apply_fit refused"; return 1; }
  python3 "$root/.tuning/verify_fit.py" "$fit" --root "$tree" | tee "$dir/verify_fit.txt"
  (( PIPESTATUS[0] == 0 )) || { say "verify_fit found the paste incomplete"; return 1; }
  if git -C "$tree" diff --quiet HEAD -- src/eval_tables.hpp src/evaluation.cpp; then
    say "nothing moved: the fit emitted the shipped constants; no SPRT is owed (S076's rule 3)"
    return 0
  fi
  python3 "$root/.tuning/diff_fit.py" "$fit" "$head" > "$dir/diff_fit.txt" 2>&1 ||
    { cat "$dir/diff_fit.txt"; say "diff_fit failed"; return 1; }
  sed -n '1,12p' "$dir/diff_fit.txt"

  # A fresh worktree's doctest submodule names an SSH URL no key answers here;
  # the main checkout's copy serves (.moltke.local.md, S254).
  if [[ -z "$(ls -A "$tree/tests/doctest" 2>/dev/null)" ]]; then
    git -C "$tree" config submodule.tests/doctest.url "$root/tests/doctest" &&
      git -C "$tree" -c protocol.file.allow=always submodule update --init \
        > "$dir/submodule.log" 2>&1 ||
      { cat "$dir/submodule.log"; say "the doctest submodule did not check out"; return 1; }
  fi

  export CLANG_FORMAT_MAJOR=22  # this machine's override, DEC-146

  # apply_fit.py writes a multi-line array back on one line, past the column
  # limit; the formatter lays it out again (layout only), as every paste
  # since S065 needed.
  ( cd "$tree" && ./clang-format.sh ) > "$dir/format_apply.log" 2>&1 ||
    { cat "$dir/format_apply.log"; say "clang-format.sh failed in $tree"; return 1; }
  git -C "$tree" diff --stat -- src | tee "$dir/diff_stat.txt"

  (
    cd "$tree" || exit 1
    [[ -d build ]] || cmake -S . -B build -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_CXX_COMPILER_LAUNCHER=ccache > /dev/null || exit 1
    [[ -d build-tune ]] || cmake -S . -B build-tune -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_CXX_COMPILER_LAUNCHER=ccache -DCHESSO_TUNE=ON > /dev/null || exit 1
    cmake --build build -j"$THREADS" > "$dir/build.log" 2>&1 || exit 2
    cmake --build build-tune -j"$THREADS" > "$dir/build_tune.log" 2>&1 || exit 3
  )
  case $? in
    0) ;;
    2) tail -20 "$dir/build.log"; say "the Release build failed (a static_assert on a packed or bounded weight fires here)"; return 1 ;;
    3) tail -20 "$dir/build_tune.log"; say "the tune build failed"; return 1 ;;
    *) say "configure failed in $tree"; return 1 ;;
  esac

  "$tree/build/src/chesso" bench > "$dir/bench.txt" 2>&1 ||
    { say "bench failed"; return 1; }
  say "bench     $(grep -E '^[0-9]+ nodes' "$dir/bench.txt" | tail -n 1 | awk '{print $1}') nodes (the commit's Bench: line)"

  (
    cd "$tree" || exit 1
    ctest --test-dir build -L fast --output-on-failure > "$dir/fast_release.log" 2>&1
    ctest --test-dir build-tune -L fast --output-on-failure > "$dir/fast_tune.log" 2>&1
    ./clang-format.sh --check > "$dir/format.log" 2>&1
    exit 0
  )
  say "fast suite, Release: $(grep -E 'tests passed|tests failed' "$dir/fast_release.log")"
  grep -E '\(Failed\)' "$dir/fast_release.log" | sed 's/^/  red  /'
  say "fast suite, tune:    $(grep -E 'tests passed|tests failed' "$dir/fast_tune.log")"
  grep -E '\(Failed\)' "$dir/fast_tune.log" | sed 's/^/  red  /'
  say "the reds are the goldens the paste moved; each is re-derived by its own script (the step file's landing list), never read off this run"
}

