# The engine a stage ran, as adocs/data/S082_recipe.sh names it: HEAD's sha,
# or on a tree with src/ or tools/ changed against HEAD, HEAD's sha plus the
# first 12 hex of the git blob id of that diff, saved at $1. Refused when an
# untracked file sits under src/ or tools/, which no diff names.
engine_stamp() {
  local head untracked
  untracked=$(git -C "$root" ls-files --others -- src tools |
                grep -v '/__pycache__/')
  if [[ -n "$untracked" ]]; then
    {
      echo "refused: untracked files under src/ or tools/, which no stamp names:"
      echo "$untracked"
    } >&2
    return 1
  fi
  head=$(git -C "$root" rev-parse --short HEAD)
  if git -C "$root" diff --quiet HEAD -- src tools; then
    echo "$head"
    return
  fi
  git -C "$root" diff --no-ext-diff --no-color --full-index --binary HEAD \
      -- src tools > "$1"
  echo "$head+$(git hash-object --no-filters "$1" | cut -c1-12), the diff at $1"
}

binary_line() {
  printf '%-9s sha256 %s\n' "$1" "$(sha256sum "$2" | cut -d' ' -f1)  $2"
}

say() { echo "$*"; }

enough_disk() {
  local free_gb
  mkdir -p "$OUT"
  free_gb=$(df --output=avail -BG "$OUT" | tail -n 1 | tr -dc '0-9')
  if (( free_gb < FREE_GB_FLOOR )); then
    say "refused: ${free_gb} GB free under $OUT, under the ${FREE_GB_FLOOR} GB a stage needs"
    return 1
  fi
}

# The datagen the run's pool is played by, once a chunk exists; until then the
# binary the build holds. Which engine that is decides MODE.
run_datagen_sha() {
  if [[ -f "$OUT/chunks/datagen.sha256" ]]; then
    cat "$OUT/chunks/datagen.sha256"
  elif [[ -x "$datagen" ]]; then
    sha256sum "$datagen" | cut -d' ' -f1
  else
    say "no datagen at $datagen"
    return 1
  fi
}

mode_of() {
  if [[ "$1" == "$S082_DATAGEN_SHA" ]]; then echo s082; else echo none; fi
}

derived_mode() {
  local sha
  sha=$(run_datagen_sha) || { echo "$sha"; return 1; }
  mode_of "$sha"
}

# MODE must say what the binary says: the sha given, by default the run's.
require_mode() {
  local sha="${1:-}" derived
  if [[ -z "$sha" ]]; then
    sha=$(run_datagen_sha) || { echo "$sha"; return 1; }
  fi
  derived=$(mode_of "$sha")
  if [[ -z "${MODE:-}" ]]; then
    say "refused: MODE is not set; the datagen binary (${sha:0:12}) says MODE=$derived (see the header)"
    return 1
  fi
  if [[ "$MODE" != "$derived" ]]; then
    say "refused: MODE=$MODE, and the datagen binary (${sha:0:12}) says $derived"
    return 1
  fi
}

# A frozen copy of a build binary under $OUT, its sha256 recorded when it is
# copied; check_copy re-hashes it against that record before every run, so a
# rebuild of build/ -- tools/gate.sh rebuilds it on any commit -- can never put
# another engine under a recorded sha. An existing copy is reused, never
# replaced. Prints the sha; on a refusal prints why.
freeze_binary() {
  local src="$1" copy="$2"
  mkdir -p "$(dirname "$copy")" || return 1
  if [[ ! -f "$copy" ]]; then
    [[ -x "$src" ]] || { echo "no binary at $src"; return 1; }
    cp "$src" "$copy.tmp" && chmod +x "$copy.tmp" || return 1
    sha256sum "$copy.tmp" | cut -d' ' -f1 > "$copy.sha256.tmp" || return 1
    mv "$copy.tmp" "$copy" && mv "$copy.sha256.tmp" "$copy.sha256" || return 1
  fi
  [[ -f "$copy.sha256" ]] || { echo "$copy has no recorded sha256"; return 1; }
  check_copy "$copy" || return 1
  cat "$copy.sha256"
}

check_copy() {
  if [[ "$(sha256sum "$1" | cut -d' ' -f1)" != "$(cat "$1.sha256")" ]]; then
    echo "refused: $1 no longer has the sha256 recorded when it was copied"
    return 1
  fi
}

check_stage_number() {
  [[ "$1" =~ ^[0-9]+$ ]] && (( $1 >= ${2:-0} && $1 <= NIGHTS )) || {
    say "refused: stage '$1' outside ${2:-0} .. $NIGHTS"
    return 1
  }
}

chunks_for() {  # stage, mode -> how many chunks the stage's pool holds
  if [[ "$2" == none && "$1" == 1 ]]; then
    echo 12
  else
