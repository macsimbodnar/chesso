#!/usr/bin/env python3
"""Re-derive the two measured constants S188 moved. DEC-142, DEC-228.

    adocs/data/S188_repair_goldens.py s207
    adocs/data/S188_repair_goldens.py s207 --lib .ref-builds/S188_parent/build/src/libchesso_engine.a
    adocs/data/S188_repair_goldens.py first-mate
    adocs/data/S188_repair_goldens.py first-mate --engine ./build/src/chesso

WHY THIS FILE EXISTS. S188's check extension makes a search reach further than
its nominal depth, and two cases in `tests/` hold a number that was measured
against a tree without one:

  `tests/test_search.cpp` "search() hands the rule the root's own index" drives
  three searches at a depth chosen so that the cycle's return to the **root's
  own** entry is inside the tree and its return to the **ply-1** position is
  not. One extension anywhere in those plies moves that depth, and the case
  cannot derive it for itself: nothing in the fixture can see which ply a
  search reached.

  `tests/test_engine.cpp` "a narrowed window still finds a mate that appears
  mid-search" holds `first_mate_depth` per position -- the iteration a mate
  score first appears at -- and its own comment says it "was found by
  measurement, not chosen" against a reference binary. It had no re-derivation
  and that absence is a DEC-142 finding this file closes.

Both stages print what the case should hold **and the whole sweep behind it**,
so a number that moves is read with its neighbours rather than on its own.

`s207` compiles a throwaway driver against the engine library as it stands --
`search_after()` of the case, line for line, in the shape of
`adocs/data/S230_mine_r01_row.py`'s `depths` and for the same reason: the case
calls `search()` at one depth and `go depth N` is a different thing (iterative
deepening, aspiration windows, a warm table). Run it once per tree; the
separating depth is the one the case drives.

`first-mate` drives the shipping binary over UCI, as the case's `deepen()` does,
and reads the depth of the first `info` line carrying a mate score. It sends
`quit` only after `bestmove` arrives (TOOLCHAIN.md's trap) and checks the two
preconditions the case asserts around the constant: the mate must first appear
above `AspirationMinDepth`, and the iteration below it must score in
centipawns. The third -- that the aspiration schedule actually failed -- is the
engine's own counter and only the case can read it.

Neither number is Elo and neither is a verdict (DEC-019).
"""

import argparse
import os
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# The case's own three searches, its two FENs and its two lines, and the range
# swept around them. `search_after(one_ply_before, forced_reply, d)` is search
# 1, the same at `d + 1` is search 2, and `search_after(root_fen, cycle, d)` is
# search 3.
DRIVER = r"""
// Generated by adocs/data/S188_repair_goldens.py. search_after() of
// tests/test_search.cpp "search() hands the rule the root's own index", line
// for line, over a depth range.
#include <atomic>
#include <cstdio>
#include <cstdlib>
#include <string>
#include <utility>
#include <vector>
#include "bitboard.hpp"
#include "data_structures.hpp"
#include "search.hpp"
#include "transposition_table.hpp"

namespace
{
game_t game;
transposition_table_t tt;
std::atomic_bool never_stop = false;

// tests/test_helpers.hpp's play_move(), copied because that header pulls in
// doctest. Same body.
bool play_move(game_t* g, index_t from, index_t to)
{
  move_t moves[MAX_MOVES];
  const size_t count = generate_moves(game_tables(), &g->board, moves);

  for (size_t i = 0; i < count; ++i) {
    if (MOVE_FROM(moves[i]) != from || MOVE_TO(moves[i]) != to) { continue; }
    if (make_move(g, moves[i])) { return true; }
  }

  return false;
}

search_t search_after(const std::string& fen,
                      const std::vector<std::pair<index_t, index_t>>& line,
                      int depth)
{
  if (!load_FEN(fen, &game)) { fprintf(stderr, "bad FEN\n"); exit(2); }

  for (const auto& [from, to] : line) {
    if (!play_move(&game, from, to)) { fprintf(stderr, "bad move\n"); exit(2); }
  }

  never_stop = false;
  tt_reset(&tt);
  tt_new_search(&tt);

  search_state_t state = {};
  state.tt = &tt;
  state.stop = &never_stop;

  return search(depth, &game, &state);
}
}  // namespace

int main()
{
  initialize_game_const_data(&game);
  tt_resize(&tt, 16);
  tt_reset(&tt);

  const std::string root_fen = "6k1/r4pp1/6p1/8/7Q/8/6K1/q7 w - - 10 40";
  const std::string one_ply_before = "8/r4ppk/6p1/8/7Q/8/6K1/q7 b - - 9 39";
  const std::vector<std::pair<index_t, index_t>> forced_reply = {{h7, g8}};
  const std::vector<std::pair<index_t, index_t>> cycle = {
      {h4, d8}, {g8, h7}, {d8, h4}, {h7, g8}};

  printf("depth\troot_recurrence\tin_tree(d+1)\tpre_root\n");

  for (int d = 2; d <= 8; ++d) {
    const int one = search_after(one_ply_before, forced_reply, d).score;
    const int two = search_after(one_ply_before, forced_reply, d + 1).score;
    const int three = search_after(root_fen, cycle, d).score;

    printf("%d\t%d\t%d\t%d\n", d, one, two, three);
  }

  return 0;
}
"""

# The case's own bound: what separates a scored repetition from the material.
MATERIAL_BOUND = -300


def cmd_s207(args):
    work = tempfile.mkdtemp(prefix="s188_s207_")
    source = os.path.join(work, "driver.cpp")
    binary = os.path.join(work, "driver")

    with open(source, "w") as handle:
        handle.write(DRIVER)

    lib = os.path.join(REPO, args.lib)
    include = os.path.join(os.path.dirname(os.path.dirname(lib)), "..", "src")

    if not os.path.isdir(include):
        include = os.path.join(REPO, "src")

    build = subprocess.run(
        ["c++", "-I", include, "-O3", "-DNDEBUG", "-std=gnu++20",
         "-march=native", "-o", binary, source, lib],
        capture_output=True, text=True)

    if build.returncode != 0:
        sys.stderr.write(build.stderr)
        return 1

    run = subprocess.run([binary], capture_output=True, text=True)
    sys.stderr.write(run.stderr)

    if run.returncode != 0:
        return run.returncode

    print(run.stdout, end="")

    # The separating depth: search 1 answers the material, search 2 one ply
    # deeper answers the draw, and search 3 at the same depth as search 1
    # answers the draw as well -- which is the pair that shows the rule reading
    # the path and not the board, and what makes search 1 non-vacuous.
    picked = None

    for line in run.stdout.splitlines()[1:]:
        depth, one, two, three = (int(cell) for cell in line.split("\t"))

        if one < MATERIAL_BOUND and two == 0 and three == 0 and picked is None:
            picked = depth

    print()
    print(f"# lib: {args.lib}")

    if picked is None:
        print("# no depth separates the three searches on this tree -- the case "
              "cannot be re-based by depth alone")
        return 1

    print(f"# separating depth: {picked}  (the case drives {picked}, "
          f"{picked + 1} and {picked})")
    return 0


POSITIONS = [
    "r3r1k1/pp3pbp/1qp1b1p1/1BB5/3P4/Q1n2N2/P4PPP/3R1K1R b - - 5 18",
    "r4k2/R7/8/8/8/8/4K3/1R6 w - - 1 2",
]


def deepen(engine, fen, depth):
    """The case's own `deepen()`: one `go depth N` and every `info score` line
    it printed, as (depth, kind, value)."""
    proc = subprocess.Popen([engine], stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, text=True, bufsize=1)

    def send(text):
        proc.stdin.write(text + "\n")
        proc.stdin.flush()

    send("uci")

    while "uciok" not in proc.stdout.readline():
        pass

    send("ucinewgame")
    send("isready")

    while "readyok" not in proc.stdout.readline():
        pass

    send("position fen " + fen)
    send("go depth %d" % depth)

    iterations = []

    while True:
        line = proc.stdout.readline()

        if not line:
            break

        token = line.split()

        if token[:2] == ["info", "score"] and "depth" in token:
            iterations.append((int(token[token.index("depth") + 1]),
                               token[2], int(token[3])))

        if line.startswith("bestmove"):
            break

    send("quit")
    proc.wait()

    return iterations


def cmd_first_mate(args):
    bad = 0

    for fen in POSITIONS:
        iterations = deepen(args.engine, fen, args.depth)

        print(fen)
        print("  " + "  ".join(f"d{d}:{kind}{value}"
                               for d, kind, value in iterations))

        mates = [d for d, kind, _ in iterations if kind == "mate"]

        if not mates:
            print("  no mate inside the swept depth -- this position no longer "
                  "carries the shape the case is about")
            bad += 1
            continue

        first = min(mates)
        below = [kind for d, kind, _ in iterations if d == first - 1]
        distances = sorted({value for d, kind, value in iterations
                            if kind == "mate" and d >= first})

        print(f"  first_mate_depth: {first}")
        print(f"  precondition 2, the iteration below scores cp: "
              f"{below == ['cp']} ({below})")
        print(f"  mate distances from there on: {distances}")

        if below != ["cp"] or len(distances) != 1:
            bad += 1

    return 1 if bad else 0


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)

    one = sub.add_parser("s207")
    one.add_argument("--lib", default="build/src/libchesso_engine.a")

    two = sub.add_parser("first-mate")
    two.add_argument("--engine", default="./build/src/chesso")
    two.add_argument("--depth", type=int, default=10)

    args = parser.parse_args()

    if args.command == "s207":
        return cmd_s207(args)

    return cmd_first_mate(args)


if __name__ == "__main__":
    sys.exit(main())
