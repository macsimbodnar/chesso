#!/usr/bin/env python3
"""S291. The multicut mined row's depth profile through the test's own
`search_fen()` driver, one tune option at a time.

    ~/.venv/chess/bin/python adocs/data/S291_row.py --repo <worktree> \\
        --lib build-tune/src/libchesso_engine.a --lo 7 --hi 12 \\
        [--fen FEN] [--set Name=Value ...]

Compiles a throwaway driver, line for line `tests/test_search.cpp`'s
`search_fen()` (a cold 4 MB table reset before each depth, one `search()` at a
fixed depth, no node limit), against the engine library named, and prints per
depth: the mate distance or `-`, the score, the nodes and the root's PV. With
`--set` the library must be a tune build's (`-DCHESSO_TUNE=ON`): each pair goes
through `search_param_set`, which refuses an unknown name or an out-of-range
value, and the driver exits 3 if it does. S230's `depths` driver is the same
search; this one adds the options and the score, which S230's does not print.

The engine's output only: no chess judgement here (CLAUDE.md).
"""
import argparse
import os
import subprocess
import sys
import tempfile

ROW = "6k1/5pp1/6np/1PP1p3/1Q2P1P1/3r1q1P/1B1R4/6K1 b - - 0 42"

DRIVER = r"""
// Generated by adocs/data/S291_row.py: tests/test_search.cpp's search_fen().
#include <atomic>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include "bitboard.hpp"
#include "data_structures.hpp"
#include "search.hpp"
#include "search_params.hpp"
#include "transposition_table.hpp"
#include "utils.hpp"

namespace
{
game_t game;
transposition_table_t tt;
std::atomic_bool never_stop = false;

search_t search_fen(const std::string& fen, int depth)
{
  if (!load_FEN(fen, &game)) {
    fprintf(stderr, "bad FEN: %s\n", fen.c_str());
    exit(2);
  }
  never_stop = false;
  tt_reset(&tt);
  tt_new_search(&tt);
  search_state_t state = {};
  state.tt = &tt;
  state.stop = &never_stop;
  state.node_limit = NODE_BUDGET_UNLIMITED;
  return search(depth, &game, &state);
}
}  // namespace

int main(int argc, char** argv)
{
  if (argc < 4) { return 2; }
  const std::string fen = argv[1];
  const int lo = atoi(argv[2]);
  const int hi = atoi(argv[3]);
  for (int i = 4; i < argc; ++i) {
#ifdef CHESSO_TUNE
    const char* eq = strchr(argv[i], '=');
    if (eq == nullptr) { return 3; }
    const std::string name(argv[i], eq - argv[i]);
    if (!search_param_set(name.c_str(), atoi(eq + 1))) {
      fprintf(stderr, "refused: %s\n", argv[i]);
      return 3;
    }
#else
    fprintf(stderr, "options need a tune build\n");
    return 3;
#endif
  }
  initialize_game_const_data(&game);
  tt_resize(&tt, 4);
  tt_reset(&tt);
  for (int depth = lo; depth <= hi; ++depth) {
    const search_t r = search_fen(fen, depth);
    std::string pv;
    for (size_t k = 0; k < r.pv.length; ++k) {
      pv += index_to_str(MOVE_FROM(r.pv.table[k]));
      pv += index_to_str(MOVE_TO(r.pv.table[k]));
      pv += ' ';
    }
    printf("d%-2d %-4s score %6d nodes %9llu pv %s\n", depth,
           r.mate_found ? ("m" + std::to_string(r.mate_in)).c_str() : "-",
           r.score, static_cast<unsigned long long>(r.explored_nodes),
           pv.c_str());
    fflush(stdout);
  }
  return 0;
}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--lib", default="build-tune/src/libchesso_engine.a")
    ap.add_argument("--fen", default=ROW)
    ap.add_argument("--lo", type=int, default=7)
    ap.add_argument("--hi", type=int, default=12)
    ap.add_argument("--set", action="append", default=[])
    ap.add_argument("--tune", action="store_true",
                    help="compile with -DCHESSO_TUNE (a tune build's library)")
    args = ap.parse_args()

    work = tempfile.mkdtemp(prefix="s291_")
    source = os.path.join(work, "driver.cpp")
    binary = os.path.join(work, "driver")
    with open(source, "w") as handle:
        handle.write(DRIVER)
    flags = ["-DCHESSO_TUNE"] if (args.tune or args.set) else []
    build = subprocess.run(
        ["c++", "-I", os.path.join(args.repo, "src"), "-O3", "-DNDEBUG",
         "-std=gnu++20", "-march=native", *flags, "-o", binary, source,
         os.path.join(args.repo, args.lib)],
        capture_output=True, text=True)
    if build.returncode != 0:
        sys.stderr.write(build.stderr)
        return 1
    run = subprocess.run([binary, args.fen, str(args.lo), str(args.hi),
                          *args.set], capture_output=True, text=True)
    sys.stderr.write(run.stderr)
    print(run.stdout, end="")
    return run.returncode


if __name__ == "__main__":
    sys.exit(main())
