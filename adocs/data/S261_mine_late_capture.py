#!/usr/bin/env python3
"""S261. Mine the position for S269's two late-capture cases of
tests/test_search.cpp, at the tree as it stands (DEC-281).

    python3 adocs/data/S261_mine_late_capture.py fens --out <pool.fen>
    python3 adocs/data/S261_mine_late_capture.py walk --fens <pool.fen> \\
        --walks 40 --seed 261 --out <walked.fen>
    python3 adocs/data/S261_mine_late_capture.py sweep --fens <pool.fen> \\
        --lo 3 --hi 10 --out <cells.tsv>
    python3 adocs/data/S261_mine_late_capture.py pick --cells <cells.tsv>

WHY. S269's cases hold two mutants of `tools/mutants/S269_late_quiets.py`:

  LQ02  the extra ply's exchange test skipped past late move pruning's count
  LQ03  the capture rule skipped past late move pruning's count

Each needs a capture searched or skipped **past the count**. S261's vector
moved that count twice: `LmpBase` 733 -> 935, so the flag sits at move 10, and
`LmpMaxLmrDepth` 8 -> 3, so it is set only below reduced depth 3. The old
position, castling.json's `rnb1qk1r/pp1Pbppp/...`, searches 8 captures ahead of
Bxf7, one short, and no drive depth gives the extra-ply case its shape any more.

WHAT EACH CASE NEEDS, read off the engine. Every number comes from the probed
node, the engine's own tables or `see_ge`; nothing here is a chess judgement.
The drive is the cases' own: the position at ply 2, the slot two plies up
planted at 20000 so the node is not improving, a cold 4 MB table, a wide
window, `negamax_probed` at a fixed depth.

  LQ02  the flag is set; a capture that gives no check and loses **exactly
        100** by `see_ge` (passes -100, fails -99) is searched at index k >= 3
        with k + 1 at or past the flag's move number; its reduced depth there
        is 2, so the capture rule's margin `SeeCaptureCoeff * 2` clears it and
        it is not pruned; its recorded reduction is `SeeLmrExtra` and its child
        keeps a ply beyond it. That is the extra ply's exchange test reached
        past the count, which is what LQ02 removes.
  LQ03  the flag is set; a capture that gives no check is skipped by the
        capture rule, and the captures searched ahead of it -- those
        `score_move` ranks above it -- put it at or past the flag's number,
        where the margin still writes it off. That is the capture rule asked
        past the count, which is what LQ03 removes.

WHERE THE POSITIONS COME FROM. Every FEN this repository already carries as
data and nothing fetched (DEC-016): `adocs/data/S018_raw.tsv`, the self-play
positions S018 recorded, first in pool order, then every FEN found in
`adocs/data/*.tsv`, `*.fen` and `*.txt` -- this project's own sets and
candidate lists -- and in `tests/assets/test_jsons/*.json`, the test-position
files S269's own position came from. S269's castling.json position is first,
so the old row is read beside the new ones. That pool -- 23142 positions --
gave no qualifying cell for either case: game positions rarely put nine
captures ahead of a losing one.

So the second pool is walked by the engine itself: from every position of the
first, `walk` plays random legal moves through the engine's own generator,
seeded and therefore reproducible, and keeps each position reached where the
side to move is not in check, has at least ten captures that promote nothing
and at least one capture `see_ge` writes off. A walk from a reachable position
stays reachable, the moves are the engine's, and nothing in the choice is a
chess judgement: a random move is not one.

THE PICK RULE, stated before the sweep: per case, the lowest drive depth with a
qualifying cell, then the first position in pool order, then the cheaper cell.
A position qualifying for both cases at its own depths is preferred, so one row
serves both (DEC-281 allows it).

THE ENGINE MEASUREMENT IS `negamax_probed()` through the release library, the
cases' own drive line for line, and not the UCI binary: the cases drive one
node at a fixed depth from a cold table.
"""

import argparse
import csv
import glob
import os
import re
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
POOL = os.path.join(REPO, "adocs", "data", "S018_raw.tsv")
OLD_ROW = "rnb1qk1r/pp1Pbppp/2p5/8/2B5/8/PPP1NnPP/RNBQK2R w KQ - 2 9"

DRIVER = r"""
// Generated by adocs/data/S261_mine_late_capture.py: the late-capture cases'
// drive of tests/test_search.cpp, line for line, over a list of FENs.
#include <atomic>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <string>
#include "bitboard.hpp"
#include "data_structures.hpp"
#include "evaluation.hpp"
#include "search.hpp"
#include "search_params.hpp"
#include "transposition_table.hpp"
#include "utils.hpp"

namespace
{
game_t game;
transposition_table_t tt;
std::atomic_bool never_stop = false;
search_state_t state = {};
search_node_probe_t probe = {};

constexpr size_t PLY = 2;
constexpr int PLANT = 20000;

int adjustment() { return LMR_NO_TT_MOVE + LMR_NOT_IMPROVING; }

int lmr_depth_at(int depth, int move_number)
{
  const int left = depth - search_lmr_adjusted_reduction_probe(
                               depth, move_number,
                               adjustment() * search_lmr_scale_probe());
  return (left > 0) ? left : 0;
}

int flag_number(int depth)
{
  for (int m = 2; m <= MAX_MOVES; ++m) {
    const int ld = lmr_depth_at(depth, m);
    if (ld < LMP_MAX_LMRDEPTH && 100 * m > search_lmp_threshold_probe(ld, false)) {
      return m;
    }
  }
  return MAX_MOVES + 1;
}

// The loss `see_ge` shows, in its own units: the smallest t > 0 with
// see_ge(-t) true, searched exactly. 0 for a capture that loses nothing.
int see_loss(move_t move)
{
  if (see_ge(&game.board, move, 0)) { return 0; }
  int lo = 0, hi = 20000;  // see_ge(-lo) false, see_ge(-hi) true
  while (hi - lo > 1) {
    const int mid = (lo + hi) / 2;
    if (see_ge(&game.board, move, -mid)) { hi = mid; } else { lo = mid; }
  }
  return hi;
}

bool drive(const std::string& fen, int depth)
{
  if (!load_FEN(fen, &game)) { return false; }
  tt_reset(&tt);
  tt_new_search(&tt);
  never_stop = false;
  state = {};
  state.tt = &tt;
  state.stop = &never_stop;
  probe = {};
  probe.ply = static_cast<int>(PLY);
  state.probe = &probe;
  state.static_evals[PLY - 2] = PLANT;
  negamax_probed(-30000, 30000, depth, PLY, &game, &state, 0, false);
  return true;
}

int index_of(move_t move)
{
  for (int i = 0; i < probe.move_count; ++i) {
    if (probe.moves[i] == move) { return i; }
  }
  return -1;
}

int rule_of(move_t move)
{
  for (int i = 0; i < probe.pruned_count; ++i) {
    if (probe.pruned_moves[i] == move) { return probe.pruned_rule[i]; }
  }
  return PRUNE_NONE;
}
}  // namespace

int main(int argc, char** argv)
{
  if (argc != 4) { fprintf(stderr, "usage: driver FENS LO HI\n"); return 2; }
  initialize_game_const_data(&game);
  tt_resize(&tt, 4);
  const int lo = atoi(argv[2]), hi = atoi(argv[3]);
  std::ifstream in(argv[1]);
  std::string fen;
  printf("case\tdepth\tmove\tloss\tindex\tahead\tlmr_depth\tflag\trule\treduction\tnodes\tfen\n");

  while (std::getline(in, fen)) {
    if (fen.empty() || fen[0] == '#') { continue; }
    if (!load_FEN(fen, &game) || is_check(&game)) { continue; }

    // The captures the cases can use: no promotion, no check given, losing
    // material by the engine's own exchange evaluation.
    move_t moves[MAX_MOVES];
    const size_t count = generate_moves(game_tables(), &game.board, moves);
    move_t late[MAX_MOVES];
    int loss[MAX_MOVES];
    int late_count = 0;
    move_t captures[MAX_MOVES];
    int capture_count = 0;

    for (size_t i = 0; i < count; ++i) {
      if (!MOVE_CAPTURE(moves[i]) || MOVE_PROMOTED(moves[i])) { continue; }
      if (!make_move(&game, moves[i])) { continue; }
      const bool gives_check = is_check(&game);
      unmake_move(&game);
      captures[capture_count++] = moves[i];
      if (gives_check) { continue; }
      const int l = see_loss(moves[i]);
      if (l > 0) { late[late_count] = moves[i]; loss[late_count++] = l; }
    }

    if (late_count == 0) { continue; }

    for (int depth = lo; depth <= hi; ++depth) {
      drive(fen, depth);
      if (!probe.skip_quiets_set) { continue; }
      if (improving_at(&state, PLY, false)) { continue; }
      const int flag = flag_number(depth);

      for (int j = 0; j < late_count; ++j) {
        const move_t c = late[j];
        const int k = index_of(c);
        const int rule = rule_of(c);

        if (k >= 0) {
          const int ld = lmr_depth_at(depth, k + 1);
          if (k >= 3 && k + 1 >= flag && loss[j] == 100 && ld == 2 &&
              rule == PRUNE_NONE && probe.reduction[k] == SEE_LMR_EXTRA &&
              probe.child_depth[k] - 1 >= SEE_LMR_EXTRA) {
            printf("LQ02\t%d\t%s\t%d\t%d\t-\t%d\t%d\t%d\t%d\t%llu\t%s\n", depth,
                   print_move(c).c_str(), loss[j], k, ld, flag, rule,
                   probe.reduction[k], (unsigned long long)state.explored_nodes,
                   fen.c_str());
          }
        } else if (rule == PRUNE_SEE_CAPTURE) {
          // The cases' own bound on a skipped move's number: the captures
          // score_move ranks above it that the node searched.
          const int mine = score_move(&game, &state, c, 0, PLY, 0);
          int ahead = 0;
          for (int i = 0; i < capture_count; ++i) {
            if (captures[i] == c) { continue; }
            if (score_move(&game, &state, captures[i], 0, PLY, 0) > mine &&
                index_of(captures[i]) >= 0) {
              ahead++;
            }
          }
          const int ld = lmr_depth_at(depth, ahead + 1);
          if (ahead + 1 >= flag && ld < SEE_CAPT_MAX_LMRDEPTH &&
              !see_ge(&game.board, c, -(SEE_CAPT_COEFF * ld))) {
            printf("LQ03\t%d\t%s\t%d\t-\t%d\t%d\t%d\t%d\t-\t%llu\t%s\n", depth,
                   print_move(c).c_str(), loss[j], ahead, ld, flag, rule,
                   (unsigned long long)state.explored_nodes, fen.c_str());
          }
        }
      }
    }
  }
  return 0;
}
"""


FEN_RE = re.compile(
    r"[rnbqkpRNBQKP1-8]+(?:/[rnbqkpRNBQKP1-8]+){7} [wb] (?:[KQkq]{1,4}|-) "
    r"(?:[a-h][36]|-) \d+ \d+")

WALKER = r"""
// Generated by adocs/data/S261_mine_late_capture.py: seeded random walks
// through the engine's own generator, keeping positions with many captures.
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <random>
#include <string>
#include "bitboard.hpp"
#include "data_structures.hpp"

game_t game;

int main(int argc, char** argv)
{
  if (argc != 4) { fprintf(stderr, "usage: walker FENS WALKS SEED\n"); return 2; }
  initialize_game_const_data(&game);
  const int walks = atoi(argv[2]);
  std::mt19937 rng(static_cast<unsigned>(atoi(argv[3])));
  std::ifstream in(argv[1]);
  std::string fen;

  while (std::getline(in, fen)) {
    if (fen.empty()) { continue; }
    for (int w = 0; w < walks; ++w) {
      if (!load_FEN(fen, &game)) { break; }
      const int plies = 2 + static_cast<int>(rng() % 30);
      for (int p = 0; p < plies; ++p) {
        move_t moves[MAX_MOVES];
        const size_t count = generate_moves(game_tables(), &game.board, moves);
        if (count == 0) { break; }
        if (!make_move(&game, moves[rng() % count])) { break; }
        if (is_check(&game)) { continue; }

        move_t now[MAX_MOVES];
        const size_t n = generate_moves(game_tables(), &game.board, now);
        int captures = 0, losing = 0;
        for (size_t i = 0; i < n; ++i) {
          if (!MOVE_CAPTURE(now[i]) || MOVE_PROMOTED(now[i])) { continue; }
          captures++;
          if (!see_ge(&game.board, now[i], 0)) { losing++; }
        }
        if (captures >= 10 && losing >= 1) {
          printf("%s\n", generate_FEN(&game.board).c_str());
        }
      }
    }
  }
  return 0;
}
"""


def compile_source(text, name):
    work = tempfile.mkdtemp(prefix="s261_late_")
    source = os.path.join(work, name + ".cpp")
    binary = os.path.join(work, name)
    with open(source, "w") as handle:
        handle.write(text)
    return source, binary


def cmd_walk(args):
    source, binary = compile_source(WALKER, "walker")
    build = subprocess.run(
        ["c++", "-I", os.path.join(REPO, "src"), "-O3", "-DNDEBUG",
         "-std=gnu++20", "-march=native", "-o", binary, source,
         os.path.join(REPO, args.lib)],
        capture_output=True, text=True)
    if build.returncode != 0:
        sys.stderr.write(build.stderr)
        return 1
    run = subprocess.run([binary, args.fens, str(args.walks), str(args.seed)],
                         capture_output=True, text=True)
    sys.stderr.write(run.stderr)
    if run.returncode != 0:
        return run.returncode
    seen, out = set(), []
    for fen in run.stdout.splitlines():
        if fen and fen not in seen:
            seen.add(fen)
            out.append(fen)
    with open(args.out, "w") as handle:
        handle.write("\n".join(out) + "\n")
    print(f"{len(out)} walked positions -> {args.out}")
    return 0


def cmd_fens(args):
    seen = {OLD_ROW}
    out = [OLD_ROW]
    sources = [POOL]
    for pattern in ("adocs/data/*.tsv", "adocs/data/*.fen", "adocs/data/*.txt",
                    "tests/assets/test_jsons/*.json"):
        sources += sorted(p for p in glob.glob(os.path.join(REPO, pattern))
                          if p != POOL)
    for path in sources:
        with open(path, errors="replace") as handle:
            for fen in FEN_RE.findall(handle.read()):
                if fen not in seen:
                    seen.add(fen)
                    out.append(fen)
    with open(args.out, "w") as handle:
        handle.write("\n".join(out) + "\n")
    print(f"{len(out)} positions -> {args.out}")
    return 0


def cmd_sweep(args):
    work = tempfile.mkdtemp(prefix="s261_late_")
    source = os.path.join(work, "driver.cpp")
    binary = os.path.join(work, "driver")
    with open(source, "w") as handle:
        handle.write(DRIVER)
    build = subprocess.run(
        ["c++", "-I", os.path.join(REPO, "src"), "-O3", "-DNDEBUG",
         "-std=gnu++20", "-march=native", "-o", binary, source,
         os.path.join(REPO, args.lib)],
        capture_output=True, text=True)
    if build.returncode != 0:
        sys.stderr.write(build.stderr)
        return 1
    run = subprocess.run([binary, args.fens, str(args.lo), str(args.hi)],
                         capture_output=True, text=True)
    sys.stderr.write(run.stderr)
    if run.returncode != 0:
        return run.returncode
    with open(args.out, "w") as handle:
        handle.write(run.stdout)
    rows = [ln for ln in run.stdout.splitlines()[1:] if ln]
    print(f"{sum(r.startswith('LQ02') for r in rows)} LQ02 cells, "
          f"{sum(r.startswith('LQ03') for r in rows)} LQ03 cells -> {args.out}")
    return 0


def cmd_pick(args):
    with open(args.cells) as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))
    order = {}
    for i, r in enumerate(rows):
        order.setdefault(r["fen"], i)

    def best(case, fens=None):
        cells = [r for r in rows if r["case"] == case
                 and (fens is None or r["fen"] in fens)]
        cells.sort(key=lambda r: (int(r["depth"]), order[r["fen"]],
                                  int(r["nodes"])))
        return cells[0] if cells else None

    both = {r["fen"] for r in rows if r["case"] == "LQ02"} & \
           {r["fen"] for r in rows if r["case"] == "LQ03"}
    for label, fens in (("one position for both", both), ("each on its own", None)):
        a, b = best("LQ02", fens), best("LQ03", fens)
        if fens is not None and not fens:
            print(f"{label}: none")
            continue
        print(f"{label}:")
        for case, cell in (("LQ02", a), ("LQ03", b)):
            if cell is None:
                print(f"  {case}: none")
            else:
                print(f"  {case}: depth {cell['depth']} {cell['move']} loss "
                      f"{cell['loss']} index {cell['index']} ahead "
                      f"{cell['ahead']} lmr_depth {cell['lmr_depth']} flag "
                      f"{cell['flag']} nodes {cell['nodes']}  {cell['fen']}")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="stage", required=True)
    one = sub.add_parser("fens")
    one.add_argument("--out", required=True)
    one.set_defaults(run=cmd_fens)
    walk = sub.add_parser("walk")
    walk.add_argument("--fens", required=True)
    walk.add_argument("--walks", type=int, default=40)
    walk.add_argument("--seed", type=int, default=261)
    walk.add_argument("--lib", default="build/src/libchesso_engine.a")
    walk.add_argument("--out", required=True)
    walk.set_defaults(run=cmd_walk)
    two = sub.add_parser("sweep")
    two.add_argument("--fens", required=True)
    two.add_argument("--lo", type=int, default=3)
    two.add_argument("--hi", type=int, default=10)
    two.add_argument("--lib", default="build/src/libchesso_engine.a")
    two.add_argument("--out", required=True)
    two.set_defaults(run=cmd_sweep)
    three = sub.add_parser("pick")
    three.add_argument("--cells", required=True)
    three.set_defaults(run=cmd_pick)
    args = parser.parse_args()
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
